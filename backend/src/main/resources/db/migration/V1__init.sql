-- Initial schema for the Whiteboard Interviewer.
-- Diagram/transcript payloads are stored as JSONB event logs for replay (PRD 6.2).

CREATE TABLE users (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email         TEXT NOT NULL UNIQUE,
    display_name  TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Question bank. `reference_solution` is non-null only for vetted entries;
-- when present the Council node is skipped for that session (PRD 6.3 / FR4).
CREATE TABLE questions (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug                TEXT NOT NULL UNIQUE,
    title               TEXT NOT NULL,
    prompt              TEXT NOT NULL,
    source              TEXT NOT NULL DEFAULT 'seed',   -- seed | generated | community
    status              TEXT NOT NULL DEFAULT 'approved', -- pending | approved | rejected
    reference_solution  JSONB,                          -- { summary, diagram:{nodes,edges}, tradeoffs[] }
    submitted_by        UUID REFERENCES users(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_questions_status ON questions(status);
CREATE INDEX idx_questions_source ON questions(source);

CREATE TABLE interview_sessions (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID REFERENCES users(id),
    question_id         UUID REFERENCES questions(id),
    state               TEXT NOT NULL DEFAULT 'active',  -- active | submitted | ended
    diagram_locked      BOOLEAN NOT NULL DEFAULT FALSE,
    -- Reference solution actually used this session (copied from bank or Council output).
    reference_solution  JSONB,
    final_diagram       JSONB,
    debrief             JSONB,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at        TIMESTAMPTZ,
    ended_at            TIMESTAMPTZ
);
CREATE INDEX idx_sessions_user ON interview_sessions(user_id);
CREATE INDEX idx_sessions_state ON interview_sessions(state);

-- Append-only event log: transcript chunks, diagram snapshots, chat turns, lock signals.
CREATE TABLE session_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   UUID NOT NULL REFERENCES interview_sessions(id) ON DELETE CASCADE,
    seq          BIGINT NOT NULL,               -- monotonic per session, for resume/ordering
    type         TEXT NOT NULL,                 -- matches WebSocket message `type`
    payload      JSONB NOT NULL,
    ts           TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (session_id, seq)
);
CREATE INDEX idx_events_session_seq ON session_events(session_id, seq);

-- Rolling interim summaries (PRD 6.3 node 4 / FR9). ~5 per 30-min session.
CREATE TABLE interim_summaries (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id   UUID NOT NULL REFERENCES interview_sessions(id) ON DELETE CASCADE,
    ordinal      INT NOT NULL,
    content      TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (session_id, ordinal)
);
